#!/usr/bin/env python3
"""Embed the OpenGL versions of shared GLSL sources (pc/shaders/vulkan) as C
strings in a generated header, so OpenGL and Vulkan run the same shader text.

    python3 pc/tools/gl_shaders.py [--out pc/build/boot/gl_shaders.h]

Compute shaders (SHADERS) become `static const char pc_glsl_<name>[]`: their
`#include "..."` lines inlined (the included files carry include guards),
`#version`/`#extension` lines dropped, and "#version 430 core" plus
"#define ROOD_GL 1" put in front. Fragments (FRAGMENTS) become string macros
`PC_GLSL_<NAME>` to splice into a larger shader string (gl_present.c's
present shader, GLSL 3.30). The header is only rewritten when it changes.
"""
import argparse
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCES = ROOT / "pc/shaders/vulkan"
# The probe GI (pc/src/probe_gi.inc) on OpenGL 4.3 compute.
SHADERS = ["probe_trace_bvh.comp", "probe_blend.comp", "probe_state.comp", "ui_mmpx.comp"]
FRAGMENTS = ["probe_common.glsl", "aa_geometry.glsl", "downsample.glsl", "ms_resolve.glsl",
             "brightness.glsl",  # the brightness setting (gl_present.c)
             "emissive.glsl",  # emissive texels (gpu_hw.c's packets, render.c's native lists)
             "text_dist.glsl",  # text and icons from distance texels (gpu_hw.c's packets, the text overlay)
             "post_grade.glsl",  # the post stack's grade pass (gl_present.c)
             "post_bloom.glsl",  # the post stack's Gaussian bloom and exposure meter (gl_present.c)
             # The room's sun and sky (ptgi.c's trace, gl_present.c's present).
             "environment.glsl",
             # The room's medium: haze, ground fog, fog volumes (ptgi.c's haze, gl_present.c's Low haze).
             "medium.glsl",
             # The menu's model view: its studio light (gl_present.c's present).
             "menu_studio.glsl",
             # The hand-placed fog volumes' own renderer (gl_present.c's per-pixel march).
             "fog_volume.glsl",
             # The port's particles' composite (gl_present.c's present).
             "particles.glsl",
             # The reference SMAA shader (MIT, pc/third_party/smaa), used through its GLSL macros.
             "../../third_party/smaa/SMAA.hlsl"]
INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"\s*$')


def inline(path, depth=0):
    if depth > 16:
        raise RuntimeError(f"{path}: includes nest too deep")
    lines = []
    # Vendored sources may carry CRLF and Latin-1 bytes in comments: plain ASCII for every driver.
    text = path.read_bytes().decode("latin-1").replace("\r", "")
    text = "".join(c if ord(c) < 128 else "?" for c in text)
    for line in text.splitlines():
        match = INCLUDE.match(line)
        if match:
            lines += inline(SOURCES / match.group(1), depth + 1)
        elif re.match(r"^\s*#\s*(version|extension)\b", line):
            continue
        else:
            lines.append(line)
    return lines


def c_string(lines):
    out = []
    for line in lines:
        escaped = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'    "{escaped}\\n"')
    return "\n".join(out) if out else '    ""'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(ROOT / "pc/build/boot/gl_shaders.h"))
    args = parser.parse_args()
    out = pathlib.Path(args.out)
    text = ["/* Generated by pc/tools/gl_shaders.py from pc/shaders/vulkan; do not edit. */",
            "#ifndef ROOD_GL_SHADERS_H", "#define ROOD_GL_SHADERS_H"]
    for name in SHADERS:
        lines = ["#version 430 core", "#define ROOD_GL 1"] + inline(SOURCES / name)
        symbol = re.sub(r"\W", "_", pathlib.Path(name).stem)
        text.append(f"static const char pc_glsl_{symbol}[] =\n{c_string(lines)};")
    for name in FRAGMENTS:
        symbol = re.sub(r"\W", "_", pathlib.Path(name).stem).upper()
        text.append(f"#define PC_GLSL_{symbol} \\\n" + c_string(inline(SOURCES / name)).replace("\n", " \\\n"))
    text.append("#endif")
    body = "\n".join(text) + "\n"
    if out.exists() and out.read_text() == body:
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_suffix(".tmp")
    tmp.write_text(body)
    os.replace(tmp, out)
    print(f"Embedded {len(SHADERS) + len(FRAGMENTS)} OpenGL shaders into {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
