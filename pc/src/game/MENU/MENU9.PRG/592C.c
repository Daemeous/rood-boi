void vs_menu9_loadZudFile(int id)
{
    static int zudId;

    vs_main_CdFile cdFile;
    int i;

    cdFile.lba = _zudLbas[id];
    zudId = id;
    cdFile.size = _zudSizes[id];
    _zudCdSlot = vs_main_allocateCdQueueSlot(&cdFile);
    _zudData = vs_main_allocHeapR(cdFile.size);

    vs_main_cdEnqueuePriority(_zudCdSlot, _zudData);

    _paletteFlag = _paletteFlags[id];
    _modelVariant = 0;

    for (i = 0; i < 6; ++i) {
        if (id == _modelVariants[i]) {
            _modelVariant = i;
            break;
        }
    }

    if (_modelVariant != 0) {
        _zudBuffer = vs_main_allocHeap(2 * VS_OBJECT_REGION);
    } else {
        _zudBuffer = vs_main_allocHeap(VS_OBJECT_REGION + 2 * sizeof(vs_battle_wepModels_t));
    }
}

int vs_menu9_parseZudFile(void)
{
    vs_battle_objectData slot;
    pc_nm_zud zud;

    if (_zudCdSlot != NULL) {
        if (_zudCdSlot->state != vs_main_CdQueueStateLoaded) {
            return 1;
        }

        vs_main_freeCdQueueSlot(_zudCdSlot);
        _zudCdSlot = NULL;

        pc_nm_zud_decode(&zud, _zudData);

        slot.dataType = 2;
        slot.index = 1;
        slot.dataAddr = (__UINTPTR_TYPE__)zud.shp.data;
        slot.modelId = zud.characterId;
        slot.destination = _zudBuffer;
        slot.actorId = 0xFF;
        slot.variant = _paletteFlag & 1;
        slot.material = zud.defaultMaterial;
        vs_battle_populateDataSlot(&slot);

        if (_modelVariant != 0) {
            slot.dataType = 1;
            slot.index = 16;
            slot.modelId = _variantMap[_modelVariant];
            slot.destination = _zudBuffer + VS_OBJECT_REGION;
            slot.actorId = 1;
            slot.unk11 = 0xFC;
            slot.variant = 0;
            vs_battle_populateDataSlot(&slot);
        } else {

            if (zud.weapon != 0) {
                slot.dataType = 4;
                slot.index = 2;
                slot.dataAddr = (__UINTPTR_TYPE__)zud.weaponWep.data;
                slot.modelId = zud.weapon;
                slot.destination = _zudBuffer + VS_OBJECT_REGION;
                slot.actorId = 1;
                slot.unk11 = 0xF0;
                slot.material = zud.weaponMaterial;
                vs_battle_populateDataSlot(&slot);
            }

            if (zud.shield != 0) {
                slot.dataType = 4;
                slot.index = 3;
                slot.dataAddr = (__UINTPTR_TYPE__)zud.shieldWep.data;
                slot.modelId = zud.shield;
                slot.destination = _zudBuffer + VS_OBJECT_REGION + sizeof(vs_battle_wepModels_t);
                slot.actorId = 1;
                slot.unk11 = 0xF1;
                slot.material = zud.shieldMaterial;
                vs_battle_populateDataSlot(&slot);
            }
        }

        if (zud.battleSeq.size != 0) {
            slot.dataType = 8;
            slot.index = 1;
            slot.dataAddr = (__UINTPTR_TYPE__)zud.battleSeq.data;
            slot.actorId = 0;
            slot.modelId = zud.weaponCategory;
            vs_battle_populateDataSlot(&slot);
        }

        if (zud.commonSeq.size != 0) {
            slot.dataType = 8;
            slot.index = 1;
            slot.dataAddr = (__UINTPTR_TYPE__)zud.commonSeq.data;
            slot.actorId = 0;
            slot.modelId = 0;
            vs_battle_populateDataSlot(&slot);
        }
        return 1;
    }

    if (_zudData == NULL) {
        return 0;
    }

    vs_battle_processObjectDataQueue();

    if (vs_battle_getEmptyObjectDataSlot() == 0) {
        vs_main_freeHeapR(_zudData);
        _zudData = NULL;
    }

    return 1;
}

void vs_menu9_freeZudFile(void)
{
    vs_main_freeHeapR(_zudBuffer);
    _zudBuffer = NULL;
}

